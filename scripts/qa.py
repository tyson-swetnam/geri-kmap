# GERI research infrastructures: every facility must belong to one.
def check_geri(conn, failures: list[str]) -> None:
    """GERI site-layer invariants.

    * every facility is a member of GERI or of a continental-ri network
      (DEIMS lists some sites in its GERI network and no RI network);
    * a harmonized-pipeline site id names exactly one facility, and a
      DEIMS id likewise (two facilities with one DEIMS id is a split
      site the loader should have kept together);
    * every network's parent exists.
    """
    if table_rows(conn, "facilities") <= 0:
        return
    no_ri = conn.execute(
        """SELECT canonical_name FROM facilities f WHERE NOT EXISTS (
             SELECT 1 FROM network_membership nm JOIN networks n USING (network_id)
             WHERE nm.facility_id = f.facility_id
               AND (n.level = 'continental-ri' OR n.network_id = 'geri'))
           ORDER BY 1""").fetchall()
    assert_true(not no_ri, f"{len(no_ri)} facilities belong neither to GERI nor to a GERI "
                           f"research infrastructure: {[r[0] for r in no_ri[:5]]}", failures)
    for scheme in ("geri-harmonized-id", "deims-id", "neon-site", "icos-station"):
        split = conn.execute(
            """SELECT value, count(DISTINCT facility_id) FROM site_identifiers
               WHERE scheme = ? GROUP BY value HAVING count(DISTINCT facility_id) > 1
               ORDER BY 1""", [scheme]).fetchall()
        assert_true(not split, f"{len(split)} {scheme} value(s) name more than one facility: "
                               f"{split[:5]}", failures)
    orphan_parent = conn.execute(
        """SELECT network_id FROM networks c WHERE parent_id IS NOT NULL
             AND NOT EXISTS (SELECT 1 FROM networks p WHERE p.network_id = c.parent_id)""").fetchall()
    assert_true(not orphan_parent, f"networks with an unknown parent: {orphan_parent}", failures)


def check_person_registry(conn, failures: list[str]) -> None:
    """Registry identity invariants. No-ops while the registry is empty.

    The non-negotiable this enforces: identity comes from persistent
    identifiers, never from names. A row with neither an ORCID nor an
    OpenAlex id cannot be re-resolved or de-duplicated later.
    """
    if table_rows(conn, "person_registry") <= 0:
        return
    no_id = conn.execute(
        "SELECT COUNT(*) FROM person_registry WHERE orcid IS NULL AND openalex_id IS NULL"
    ).fetchone()[0]
    assert_true(no_id == 0,
                f"{no_id} person_registry rows have neither orcid nor openalex_id", failures)

    bad_key = conn.execute(
        """SELECT COUNT(*) FROM person_registry
           WHERE canonical_id NOT LIKE 'orcid:%' AND canonical_id NOT LIKE 'openalex:%'"""
    ).fetchone()[0]
    assert_true(bad_key == 0,
                f"{bad_key} person_registry rows have a malformed canonical_id", failures)

    bad_tier = conn.execute(
        "SELECT COUNT(*) FROM person_registry WHERE tier NOT IN ('core', 'archive')"
    ).fetchone()[0]
    assert_true(bad_tier == 0,
                f"{bad_tier} person_registry rows have an unknown tier", failures)

    # An ORCID-keyed row must carry that ORCID; catches key/field drift.
    key_drift = conn.execute(
        """SELECT COUNT(*) FROM person_registry
           WHERE canonical_id LIKE 'orcid:%'
             AND canonical_id <> 'orcid:' || orcid"""
    ).fetchone()[0]
    assert_true(key_drift == 0,
                f"{key_drift} person_registry rows whose canonical_id disagrees with orcid",
                failures)


