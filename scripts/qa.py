# Country bounding boxes, one row per polygon part of each Natural Earth
# admin-0 country (so an overseas territory is its own box), padded by
# PAD_DEG. Generated by scripts/build_country_bbox.py; a facility is
# misplaced only when it falls outside EVERY box of its country.
COUNTRY_BBOX_CSV = Path(__file__).resolve().parent.parent / "schema" / "vocab" / "country_bbox.csv"


def load_country_boxes() -> dict[str, list[tuple[float, float, float, float]]]:
    import csv as _csv                                    # noqa: PLC0415
    boxes: dict[str, list[tuple[float, float, float, float]]] = {}
    if not COUNTRY_BBOX_CSV.exists():
        return boxes
    with COUNTRY_BBOX_CSV.open(newline="") as fh:
        for r in _csv.DictReader(fh):
            boxes.setdefault(r["iso2"], []).append(
                (float(r["min_lat"]), float(r["max_lat"]), float(r["min_lng"]), float(r["max_lng"])))
    return boxes


def assert_true(cond: bool, msg: str, failures: list[str]) -> None:
    if not cond:
        failures.append(msg)


